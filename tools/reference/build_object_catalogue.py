"""Generate reviewed OBJECT type/factory declarations without runtime I/O."""
import argparse
import hashlib
import json
from pathlib import Path


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source',required=True,type=Path)
    parser.add_argument('--review',required=True,type=Path)
    parser.add_argument('--out',required=True,type=Path)
    args=parser.parse_args()
    source=json.loads(args.source.read_text('utf-8'));review=json.loads(args.review.read_text('utf-8'))
    assert review['accepted'] is True and not review['blockers']
    assert sha(args.source) in review['filesSha256'].values()
    kinds={'org.eclipse.elk.core.math.KVector':'vector',
           'org.eclipse.elk.core.math.KVectorChain':'vector_chain',
           'org.eclipse.elk.core.math.ElkPadding':'insets',
           'org.eclipse.elk.core.math.ElkMargin':'insets',
           'org.eclipse.elk.core.util.IndividualSpacings':'individual_spacings'}
    rows=[]
    for row in source['objectDeclarations']:
        available=row['factory']['outcome']=='returned'
        kind=kinds[row['clazz']] if available else 'opaque'
        rows.append((row['id'],kind,tuple(row['targets']),row['clazz'],available))
    assert len(rows)==len({row[0]for row in rows})==18 and sum(row[4]for row in rows)==10
    text=('# SPDX-License-Identifier: EPL-2.0 OR GPL-3.0-or-later\n'
          '# Copyright Kiel University and others; OBJECT type/factory declarations.\n'
          '# Source packet SHA256: '+sha(args.source)+'\n'
          '# Generated by tools/reference/build_object_catalogue.py.\n'
          '# Fields: id, parser kind, targets, source class, raw factory available.\n'
          'OBJECT_DECLARATIONS = (\n'+''.join('    '+repr(row)+',\n' for row in rows)+')\n')
    args.out.parent.mkdir(parents=True,exist_ok=True)
    with args.out.open('x',encoding='utf-8',newline='\n')as out:out.write(text)
    print(json.dumps({'output':str(args.out),'sha256':sha(args.out),'objects':18,
                      'rawFactoriesAvailable':10,'sourceRawFactoriesUnavailable':8,'layoutExecuted':False}))


if __name__=='__main__':main()
