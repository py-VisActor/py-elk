"""Emit private static declarations from an independently reviewed source packet.

This development tool does not run a layout, register a provider, infer effective
runtime defaults, or read references from the Python package at runtime.
"""
import argparse
import hashlib
import json
from pathlib import Path


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def declaration(row):
    kinds = {'STRING': 'string', 'BOOLEAN': 'boolean', 'INT': 'integer',
             'DOUBLE': 'signed_number', 'ENUM': 'enum_ordinal', 'ENUMSET': 'enumset'}
    kind = kinds[row['type']]
    default = row['declaredDefault']
    if kind == 'enum_ordinal' and default is not None:
        default = default['enum']
    elif kind == 'enumset' and default is not None:
        default = tuple(value['enum'] for value in default['sequence'])
    elif kind == 'signed_number' and default is not None:
        default = float(default)
    elif kind == 'integer' and default is not None:
        assert type(default) is int
    assert default is None or type(default) in (str, bool, int, float, tuple)
    return (row['id'], kind, default, tuple(row['targets']), tuple(row['enumValues']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    parser.add_argument('--review', type=Path, action='append', required=True)
    parser.add_argument('--out', type=Path, required=True)
    args = parser.parse_args()
    packet = json.loads(args.source.read_text('utf-8'))
    source_hash = digest(args.source)
    for path in args.review:
        review = json.loads(path.read_text('utf-8'))
        if review.get('accepted') is not True or review.get('blockers'):
            raise ValueError('Independent source review must be accepted: ' + str(path))
        if review.get('sourceDataApproved') is not True or review.get('counts', {}).get('approvedNonObjectDeclarations') != 225:
            raise ValueError('Review must explicitly cover all225 scalar declarations: ' + str(path))
        if source_hash not in review.get('filesSha256', {}).values():
            raise ValueError('Review does not bind this exact source packet: ' + str(path))
    rows = [declaration(row) for row in packet['originalMetadataRows'] if row['type'] != 'OBJECT']
    assert len(rows) == len({row[0] for row in rows}) == 225
    text = (
        '# SPDX-License-Identifier: EPL-2.0 OR GPL-3.0-or-later\n'
        '# Copyright Kiel University and others; static ELK option declarations.\n'
        '# Source packet SHA256: ' + source_hash + '\n'
        '# Generated by tools/reference/build_scalar_catalogue.py.\n'
        '# Metadata defaults only; actual Core/provider property owners are separate.\n'
        '# Tuple fields: canonical id, native parser kind, metadata default, targets, enum values.\n'
        'SCALAR_DECLARATIONS = (\n'
        + ''.join('    ' + repr(row) + ',\n' for row in rows) + ')\n'
    )
    args.out.parent.mkdir(parents=True, exist_ok=True)
    with args.out.open('x', encoding='utf-8', newline='\n') as output:
        output.write(text)
    print(json.dumps({'output': str(args.out), 'sha256': digest(args.out),
                      'declarations': len(rows), 'runtimeIntegrated': False,
                      'layoutExecuted': False, 'fullValidation': False}))


if __name__ == '__main__':
    main()
