"""Compile fixed-source processor logging names; build tool, never runtime.

Usage: python tools/reference/generate_layered_processor_classes.py OUT
"""
import base64
import hashlib
import json
from pathlib import Path
import re
import sys

ROOT=Path(__file__).resolve().parents[2]
SOURCE='references/next-layered-processor-classes-sources.json'
SOURCE_SHA='6a71c28f254f78d0ddffafe636c665ca43f538b914f03421a43d5bdc9f0f10b1'
WORKER_SHA='275e6caf4af71c06f5afd673939bdb4c9a0edf6ad97b32476cb7bc6cfdc09d86'


def compile_names():
    raw=(ROOT/SOURCE).read_bytes()
    assert hashlib.sha256(raw).hexdigest()==SOURCE_SHA,'Processor source gate changed'
    source=json.loads(raw);assert source['workerSha256']==WORKER_SHA
    for s in source['factorySpans']:
        assert hashlib.sha256(base64.b64decode(s['sourceBytesBase64'])).hexdigest()==s['sha256']
    names={}
    for row in source['classDeclarations']:
        raw=base64.b64decode(row['sourceBytesBase64'])
        assert hashlib.sha256(raw).hexdigest()==row['sha256']
        match=re.search(rb"= createForClass\('([^']+)', '([^']+)',",raw)
        assert match and match[2].decode()==row['constructor']
        assert match[1].decode()+'.'+match[2].decode()==row['className']
        assert row['constructor']not in names
        names[row['constructor']]=row['className']
    observation=source['actualObservation'];raw=(ROOT/observation['path']).read_bytes()
    assert hashlib.sha256(raw).hexdigest()==observation['sha256']
    actual=json.loads(raw)
    assert actual['workerSha256']==WORKER_SHA
    assert actual['requestSha256']==observation['requestSha256']and actual['probeSha256']==observation['probeSha256']
    assert actual['observation']['metadataOnly']and not actual['observation']['phaseMathExecuted']
    assert len(names)==84 and set(names.values())==set(actual['observation']['uniqueClassNames'])
    factories={}
    for row in actual['observation']['rows']:
        key=(row['family'],row['name']);assert key not in factories and row['className']in names.values()
        factories[key]=row['className']
    assert len(factories)==90
    return names,factories


def main():
    names,factories=compile_names()
    out=Path(sys.argv[1])
    lines=['# SPDX-License-Identifier: EPL-2.0 OR GPL-3.0-or-later',
        '# Copyright Kiel University and others. Fixed elkjs0.12.1 metadata.',
        '# Generated by tools/reference/generate_layered_processor_classes.py.',
        '# Class names only; no processor body/support or reflection facade claim.',
        'SOURCE_SHA256 = '+repr(SOURCE_SHA), 'WORKER_SHA256 = '+repr(WORKER_SHA),
        '', 'PROCESSOR_CLASS_NAMES = {']
    lines.extend('    '+repr(k)+': '+repr(v)+','for k,v in sorted(names.items()))
    lines.extend(['}', '', 'FACTORY_PROCESSOR_CLASS_NAMES = {'])
    lines.extend('    '+repr(k)+': '+repr(v)+','for k,v in sorted(factories.items()))
    lines.extend(['}', ''])
    with out.open('x',encoding='utf-8')as handle:handle.write('\n'.join(lines))
    print(json.dumps(dict(out=str(out),classes=len(names),factories=len(factories),
        sha256=hashlib.sha256(out.read_bytes()).hexdigest(),phaseMathExecuted=False)))


if __name__=='__main__':main()
